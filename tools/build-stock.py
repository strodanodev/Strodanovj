# Builds the STRODANO stock pack for the web edition (web/stock.js uses it):
#   web/stock-images.js  the logos and the duo cut-out as WebP data URLs, so they load into WebGL even from file://
#   web/stock/*.mp4|mov  the stock videos, copied (git-ignored: too big for the repository)
# Usage: python tools/build-stock.py [source folder]   (default: ../strodano assets)
import base64, io, os, shutil, sys
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
web = os.path.join(here, '..', 'web')
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', '..', 'strodano assets')
IMAGES = [  # (stock name, source file, max width)
    ('strodano-logo.webp', 'strodano main logo.png', 1015),
    ('strodano-logo-glow.webp', 'strodano supporting logo.png', 1400),
    ('strodano-duo.webp', 'strodano duo cutout.webp', 1200),
    ('audius-logo.webp', 'sponsor logo.png', 529),
]
VIDEOS = [('strodano-top.mp4', 'top section.mp4'), ('strodano-mid.mov', 'mid section.MOV')]

out = ['// Generated by tools/build-stock.py - do not edit. STRODANO stock images as data URLs (web/stock.js).', "'use strict';", 'const STOCK_IMAGES = {']
for name, f, mw in IMAGES:
    p = os.path.join(src, f)
    if not os.path.exists(p): print('missing', p); continue
    im = Image.open(p).convert('RGBA')
    if im.width > mw: im = im.resize((mw, round(im.height * mw / im.width)), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, 'WEBP', quality=88, method=6)
    out.append("  '%s': 'data:image/webp;base64,%s'," % (name, base64.b64encode(b.getvalue()).decode()))
    print(name, im.size, len(b.getvalue()) // 1024, 'KB')
out.append('};')
open(os.path.join(web, 'stock-images.js'), 'w', newline='\n').write('\n'.join(out) + '\n')
os.makedirs(os.path.join(web, 'stock'), exist_ok=True)
for name, f in VIDEOS:
    p, d = os.path.join(src, f), os.path.join(web, 'stock', name)
    if os.path.exists(p) and (not os.path.exists(d) or os.path.getsize(d) != os.path.getsize(p)): shutil.copyfile(p, d); print('copied', name)
